"""Render a complete, runnable Townlight module project from one ``ModuleSpec``.

The plan is pure: ``plan_module_project`` returns the exact file list and text
and touches nothing. ``generate_module_project`` then refuses unsafe targets,
refuses existing targets, re-checks every planned path for containment and only
then writes. Nothing is imported, installed or executed on the host, and no
secret or default credential is ever emitted — the generated app refuses to serve
until the operator supplies a token map through the environment.
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath, PureWindowsPath

from civiccore.scaffold.spec import (
    InvalidModuleSpecError,
    ModuleSpec,
    PathContainmentError,
    ScaffoldOptions,
    TargetExistsError,
    UnsafeTargetError,
)

AGPL_SPDX = "# SPDX-License-Identifier: AGPL-3.0-only"
GENERATOR_VERSION = "1.0.0"


@dataclass(frozen=True)
class PlannedFile:
    """One file the generator will create, relative to the project root."""

    relative_path: str
    content: str
    executable: bool = False

    @property
    def size_bytes(self) -> int:
        return len(self.content.encode("utf-8"))


@dataclass(frozen=True)
class ProjectPlan:
    spec: ModuleSpec
    project_root_name: str
    files: tuple[PlannedFile, ...] = field(default_factory=tuple)

    @property
    def relative_paths(self) -> tuple[str, ...]:
        return tuple(item.relative_path for item in self.files)


@dataclass(frozen=True)
class GenerationResult:
    spec: ModuleSpec
    project_root: Path
    created: tuple[str, ...]
    dry_run: bool


def _manifest_payload(spec: ModuleSpec) -> dict[str, object]:
    """The exact manifest the generated project ships as data.

    Shaped to validate through the shipped ``civiccore.platform.ModuleManifest``
    and its Windows-local profile check; the generator asserts that before it
    returns a plan, so a template drift cannot silently produce an invalid
    module.
    """

    return {
        "module_id": spec.module_id,
        "name": spec.name,
        "version": spec.version,
        "package_name": spec.package_name,
        "civiccore_min_version": spec.civiccore_min_version,
        "enabled_by_default": False,
        "surfaces": ["staff"],
        "install_profiles": ["windows_local", "developer"],
        "dependencies": [{"module_id": "civiccore", "required": False}],
        "routes": [
            {
                "id": "home",
                "path": spec.route,
                "label": spec.name,
                "surface": "staff",
                "permission": spec.permission,
            }
        ],
        "permissions": [
            {
                "key": spec.permission,
                "label": f"Use {spec.name}",
                "description": f"Grants access to the {spec.name} staff surface.",
                "surface": "staff",
                "roles": list(spec.staff_roles),
            }
        ],
        "services": [],
        "migrations": [
            {
                "id": spec.baseline_revision,
                "description": f"Creates the {spec.package_name} module schema.",
                "owner_schema": None,
                "required": True,
            }
        ],
        "health_checks": [],
        "backup_hooks": [],
        "model_requirements": [],
        "runtime_requirements": [],
        "settings_schema_version": None,
        "metadata": {
            "generated_by": f"civiccore.scaffold {GENERATOR_VERSION}",
            "license": "AGPL-3.0-only",
        },
    }


