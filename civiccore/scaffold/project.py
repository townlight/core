def _roles_tuple_text(spec: ModuleSpec) -> str:
    return ", ".join(f'"{role}"' for role in spec.staff_roles)


def plan_module_project(spec: ModuleSpec) -> ProjectPlan:
    """Return the complete file plan for ``spec`` without touching the filesystem."""

    rendered = {
        "spdx": AGPL_SPDX,
        "module_id": spec.module_id,
        "package_name": spec.package_name,
        "name": spec.name,
        "description": spec.description,
        "version": spec.version,
        "civiccore_min_version": spec.civiccore_min_version,
        "permission": spec.permission,
        "route": spec.route,
        "token_roles_env_var": spec.token_roles_env_var,
        "baseline_revision": spec.baseline_revision,
        "roles_tuple": _roles_tuple_text(spec),
        "generator_version": GENERATOR_VERSION,
    }
    first_role = spec.staff_roles[0]

    files = [
        PlannedFile(
            "pyproject.toml",
            _PYPROJECT.format(**rendered),
        ),
        PlannedFile(
            f"src/{spec.package_name}/__init__.py",
            _INIT.format(**rendered),
        ),
        PlannedFile(
            f"src/{spec.package_name}/manifest.py",
            _MANIFEST_MODULE.format(**rendered),
        ),
        PlannedFile(
            f"src/{spec.package_name}/manifest.json",
            json.dumps(_manifest_payload(spec), indent=2, sort_keys=True) + "\n",
        ),
        PlannedFile(
            f"src/{spec.package_name}/app.py",
            _APP.format(**rendered),
        ),
        PlannedFile(
            "migrations/env.py",
            _MIGRATION_ENV.format(**rendered),
        ),
        PlannedFile(
            f"migrations/versions/{spec.baseline_revision}.py",
            _MIGRATION_BASELINE.format(**rendered),
        ),
        PlannedFile(
            f"tests/test_{spec.package_name}_contract.py",
            _TEST_CONTRACT.format(**{**rendered, "role": first_role}),
        ),
        PlannedFile(
            "docs/module.md",
            _DOCS.format(**{**rendered, "roles_text": ", ".join(spec.staff_roles)}),
        ),
        PlannedFile("README.md", _README.format(**rendered)),
        PlannedFile(".gitignore", _GITIGNORE),
    ]

    plan = ProjectPlan(spec=spec, project_root_name=spec.module_id, files=tuple(files))
    _assert_contained(plan)
    _assert_manifest_valid(spec)
    return plan


def _assert_manifest_valid(spec: ModuleSpec) -> None:
    from civiccore.platform.modules import ModuleManifest, validate_windows_local_manifest

    manifest = validate_windows_local_manifest(ModuleManifest.model_validate(_manifest_payload(spec)))
    if manifest.module_id != spec.module_id:  # pragma: no cover - defensive
        raise InvalidModuleSpecError("generated manifest does not match the requested module id")


def _assert_contained(plan: ProjectPlan) -> None:
    """Reject any planned path that is absolute, parented or platform-absolute.

    Checked before writing, so containment is a property of the plan rather than a
    hope about string formatting.
    """

    if not plan.files:
        raise PathContainmentError("plan must contain at least one file")
    seen: set[str] = set()
    for item in plan.files:
        relative = item.relative_path
        posix = PurePosixPath(relative)
        windows = PureWindowsPath(relative)
        if not relative or relative in seen:
            raise PathContainmentError(f"empty or duplicate planned path: {relative!r}")
        seen.add(relative)
        if (
            posix.is_absolute()
            or windows.is_absolute()
            or windows.drive
            or ".." in posix.parts
            or "\\" in relative
            or relative.startswith("/")
        ):
            raise PathContainmentError(f"planned path escapes the project root: {relative!r}")
        if ":" in posix.parts[0]:
            raise PathContainmentError(f"planned path names a drive: {relative!r}")


def _safe_project_root(target_directory: Path, project_root_name: str) -> Path:
    """Resolve and vet the destination, refusing anything but a fresh child directory."""

    if ".." in PurePosixPath(project_root_name).parts or "/" in project_root_name:
        raise UnsafeTargetError(f"refusing project directory name {project_root_name!r}")

    base = Path(target_directory)
    if not base.is_absolute():
        base = Path.cwd() / base
    base = base.resolve(strict=False)
    if base.exists() and not base.is_dir():
        raise UnsafeTargetError(f"target {base} exists and is not a directory")
    project_root = base / project_root_name

    if project_root.is_symlink() or (project_root.exists() and project_root.is_file()):
        raise UnsafeTargetError(
            f"{project_root} exists and is a file; refusing to treat it as a project directory"
        )
    if project_root.exists():
        raise TargetExistsError(
            f"{project_root} already exists; the generator never overwrites an existing project"
        )

    # Resolve the parent to make sure symlinked bases cannot redirect the write.
    resolved_parent = project_root.parent.resolve(strict=False)
    if resolved_parent != base:
        raise PathContainmentError(
            f"{project_root.parent} resolves outside the requested target directory {base}"
        )
    if project_root.parent != project_root.resolve(strict=False).parent:
        raise PathContainmentError(f"{project_root} would not be created where requested")
    return project_root


def generate_module_project(
    spec: ModuleSpec,
    target_directory: Path,
    *,
    options: ScaffoldOptions | None = None,
) -> GenerationResult:
    """Create the project on disk, or refuse. Existing targets are never merged."""

    options = options or ScaffoldOptions()
    plan = plan_module_project(spec)
    project_root = _safe_project_root(Path(target_directory), plan.project_root_name)

    if options.dry_run:
        return GenerationResult(
            spec=spec, project_root=project_root, created=plan.relative_paths, dry_run=True
        )

    created: list[str] = []
    try:
        for item in plan.files:
            destination = project_root / item.relative_path
            resolved = destination.resolve(strict=False)
            if project_root not in resolved.parents:
                raise PathContainmentError(
                    f"{item.relative_path!r} resolves outside {project_root}"
                )
            destination.parent.mkdir(parents=True, exist_ok=True)
            with open(destination, "x", encoding="utf-8", newline="\n") as handle:
                handle.write(item.content)
            created.append(item.relative_path)
    except BaseException:
        _rollback(project_root, created)
        raise

    return GenerationResult(
        spec=spec, project_root=project_root, created=tuple(created), dry_run=False
    )


def _rollback(project_root: Path, created: list[str]) -> None:
    """Remove only what this call created, then the directories it made."""

    for relative in reversed(created):
        try:
            os.remove(project_root / relative)
        except OSError:  # pragma: no cover - defensive
            pass
    for directory in sorted(
        (path for path in project_root.rglob("*") if path.is_dir()),
        key=lambda path: len(path.parts),
        reverse=True,
    ):
        try:
            directory.rmdir()
        except OSError:  # pragma: no cover - defensive
            pass
    try:
        project_root.rmdir()
    except OSError:  # pragma: no cover - defensive
        pass
